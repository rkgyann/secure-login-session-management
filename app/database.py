import sqlite3
from pathlib import Path
from flask import current_app, g

class PostgresAdapter:
    def __init__(self, url):
        import psycopg
        from psycopg.rows import dict_row
        self.conn = psycopg.connect(url, row_factory=dict_row)
    def execute(self, sql, args=()):
        if sql.strip().upper() == 'BEGIN IMMEDIATE':
            return self.conn.execute('SELECT pg_advisory_xact_lock(61709342)')
        return self.conn.execute(sql.replace('?', '%s'), args)
    def commit(self): self.conn.commit()
    def close(self): self.conn.close()

def get_db():
    if 'db' not in g:
        url = current_app.config.get('DATABASE_URL')
        if url:
            g.db = PostgresAdapter(url)
        else:
            g.db = sqlite3.connect(current_app.config['DATABASE'], timeout=10)
            g.db.row_factory = sqlite3.Row
            g.db.execute('PRAGMA foreign_keys = ON')
    return g.db

def init_db():
    db = get_db()
    schema = Path(__file__).with_name('schema.sql').read_text()
    if isinstance(db, PostgresAdapter):
        schema = schema.replace('id INTEGER PRIMARY KEY,', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,')
        schema = schema.replace('user_id INTEGER REFERENCES users(id)', 'user_id BIGINT REFERENCES users(id)')
        schema = schema.replace('user_id INTEGER NOT NULL REFERENCES users(id)', 'user_id BIGINT NOT NULL REFERENCES users(id)')
        for statement in schema.split(';'):
            if statement.strip(): db.execute(statement)
    else:
        db.executescript(schema)
    db.commit()

def close_db(error=None):
    db = g.pop('db', None)
    if db is not None: db.close()
